#!/bin/sh
# Replay the vendor (LK) IT6112 init sequence on a live device via i2cpeek.
# Values and order come from the LK disassembly (see docs/it6112-vendor-init.md).
# Usage: ./vendor-it6112.sh [rx|tx|dcs|all]
B=3; RX=0x5e; TX=0x56
P=/root/i2cpeek

rd() { $P $B $1 $2 1 2>/dev/null | cut -d: -f2; }
wr() { $P -w $B $1 $2 $3 >/dev/null 2>&1; }
rmw() { # addr reg andmask ormask
	v=$(rd $1 $2); nv=$(( 0x$v & $3 | $4 )); wr $1 $2 $(printf '0x%02x' $nv); }

dcs() { # 4 bytes then trigger
	for b in $1 $2 $3 $4; do wr $TX 0x73 $b; done
	wr $TX 0x75 0x87
}

rx_init() {
	wr $RX 0x09 0xff
	wr $RX 0x0a 0xff
	wr $RX 0x0b 0x3f
	wr $RX 0x05 0x03
	wr $RX 0x05 0x00
	rmw $RX 0x0c 0xf0 0x03
	rmw $RX 0x11 0xfe 0x01
	wr $RX 0x18 0x43
	rmw $RX 0x19 0x0c 0x03
	rmw $RX 0x20 0x08 0x03
	rmw $RX 0x21 0xf7 0x08
	rmw $RX 0x44 0xdd 0x22
	wr $RX 0x27 0x3e
	wr $RX 0x72 0x07
	rmw $RX 0x8a 0xf8 0x02
	rmw $RX 0xa0 0xfe 0x01
	rmw $RX 0x80 0xc0 0x07
	sleep 0.05
}

tx_init() {
	wr $TX 0x05 0xfe
	wr $TX 0x05 0x00
	rmw $TX 0x05 0xfe 0x01
	rmw $TX 0x05 0xdf 0x20
	rmw $TX 0xd0 0x03 0x00
	rmw $TX 0x21 0xfd 0x02
	wr $TX 0x23 0x00
	rmw $TX 0x24 0xf0 0x01
	wr $TX 0x25 0x00
	rmw $TX 0x26 0xf0 0x01
	rmw $TX 0x3c 0xf0 0x03
	rmw $TX 0x10 0xdf 0x20
	wr $TX 0x22 0x30
	rmw $TX 0x11 0xef 0x00
	rmw $TX 0x10 0xfd 0x00
	rmw $TX 0x11 0xf7 0x00
	rmw $TX 0x3c 0xdf 0x20
	rmw $TX 0x44 0xfb 0x04
	rmw $TX 0x45 0xf0 0x04
	rmw $TX 0x47 0x0f 0x10
	wr $TX 0xb0 0x27
	wr $TX 0x1f 0x0b
}

dcs_on() {
	dcs 0x05 0x11 0x00 0x36
	sleep 0.15
	dcs 0x05 0x29 0x00 0x1c
	sleep 0.05
	rmw $TX 0x44 0xfe 0x01
	wr $TX 0x05 0xfe
	rmw $TX 0x06 0xfb 0x04
	wr $TX 0x05 0x00
}

case ${1:-all} in
	rx)  rx_init ;;
	tx)  tx_init ;;
	dcs) dcs_on ;;
	*)   rx_init; tx_init; dcs_on ;;
esac
echo "done: ${1:-all}"
echo "0x5e: $(rd $RX 0x18) $(rd $RX 0x21) $(rd $RX 0x80)"
echo "0x56: 0x22=$(rd $TX 0x22) 0x1f=$(rd $TX 0x1f) 0x05=$(rd $TX 0x05) 0x45=$(rd $TX 0x45)"
